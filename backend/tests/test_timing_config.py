from app.core.config_admin import CONFIG_FIELD_MAP


def test_timing_config_fields_are_registered():
    assert "ENABLE_TIMING_LOGS" in CONFIG_FIELD_MAP
    assert "EXPOSE_TIMINGS_IN_API" in CONFIG_FIELD_MAP
    assert "TASK_LLM_BASE_URL" in CONFIG_FIELD_MAP
    assert "TASK_LLM_API_KEY" in CONFIG_FIELD_MAP
    assert "TASK_LLM_MODEL_NAME" in CONFIG_FIELD_MAP
    assert "SEARCH_DEFAULT_TOP_K" in CONFIG_FIELD_MAP
    assert "SEARCH_ENABLE_SCORE_FILTER" in CONFIG_FIELD_MAP
    assert "SEARCH_MIN_RELEVANCE_SCORE" in CONFIG_FIELD_MAP
    assert "CHAT_DEFAULT_TOP_K" in CONFIG_FIELD_MAP
    assert "CHAT_FAST_DEFAULT_TOP_K" in CONFIG_FIELD_MAP
    assert "CHAT_FAST_DISABLE_QUERY_REWRITE" in CONFIG_FIELD_MAP
    assert "CHAT_FAST_DISABLE_RERANK" in CONFIG_FIELD_MAP
    assert "CHAT_FAST_DISABLE_CONTEXT_COMPRESSION" in CONFIG_FIELD_MAP
    assert "CHAT_FAST_FORCE_TRUE_STREAMING" in CONFIG_FIELD_MAP
    assert "CHAT_EXPERT_DEFAULT_TOP_K" in CONFIG_FIELD_MAP
    assert "CHAT_EXPERT_RERANK_CANDIDATE_K" in CONFIG_FIELD_MAP
    assert "CHAT_EXPERT_QUERY_MULTI_COUNT" in CONFIG_FIELD_MAP
    assert "CHAT_EXPERT_FORCE_QUERY_REWRITE" in CONFIG_FIELD_MAP
    assert "CHAT_EXPERT_FORCE_RERANK" in CONFIG_FIELD_MAP
    assert "CHAT_EXPERT_FORCE_CONTEXT_COMPRESSION" in CONFIG_FIELD_MAP
    assert "CHAT_EXPERT_FORCE_TRUE_STREAMING" in CONFIG_FIELD_MAP
    assert "CHAT_ENABLE_SCORE_FILTER" in CONFIG_FIELD_MAP
    assert "CHAT_MIN_RELEVANCE_SCORE" in CONFIG_FIELD_MAP
    assert "CHAT_EXPERT_FORCE_AGENTIC_RAG" in CONFIG_FIELD_MAP
    assert CONFIG_FIELD_MAP["ENABLE_TIMING_LOGS"].parse_as == "bool"
    assert CONFIG_FIELD_MAP["EXPOSE_TIMINGS_IN_API"].parse_as == "bool"
    assert CONFIG_FIELD_MAP["TASK_LLM_BASE_URL"].group == "models"
    assert CONFIG_FIELD_MAP["TASK_LLM_API_KEY"].sensitive is True
    assert CONFIG_FIELD_MAP["SEARCH_ENABLE_SCORE_FILTER"].parse_as == "bool"
    assert CONFIG_FIELD_MAP["CHAT_MIN_RELEVANCE_SCORE"].parse_as == "float"
    assert CONFIG_FIELD_MAP["CHAT_FAST_DEFAULT_TOP_K"].parse_as == "int"
    assert CONFIG_FIELD_MAP["CHAT_FAST_DISABLE_QUERY_REWRITE"].parse_as == "bool"
    assert CONFIG_FIELD_MAP["CHAT_FAST_DISABLE_RERANK"].parse_as == "bool"
    assert CONFIG_FIELD_MAP["CHAT_FAST_DISABLE_CONTEXT_COMPRESSION"].parse_as == "bool"
    assert CONFIG_FIELD_MAP["CHAT_FAST_FORCE_TRUE_STREAMING"].parse_as == "bool"
    assert CONFIG_FIELD_MAP["CHAT_EXPERT_DEFAULT_TOP_K"].parse_as == "int"
    assert CONFIG_FIELD_MAP["CHAT_EXPERT_RERANK_CANDIDATE_K"].parse_as == "int"
    assert CONFIG_FIELD_MAP["CHAT_EXPERT_QUERY_MULTI_COUNT"].parse_as == "int"
    assert CONFIG_FIELD_MAP["CHAT_EXPERT_FORCE_QUERY_REWRITE"].parse_as == "bool"
    assert CONFIG_FIELD_MAP["CHAT_EXPERT_FORCE_RERANK"].parse_as == "bool"
    assert CONFIG_FIELD_MAP["CHAT_EXPERT_FORCE_CONTEXT_COMPRESSION"].parse_as == "bool"
    assert CONFIG_FIELD_MAP["CHAT_EXPERT_FORCE_TRUE_STREAMING"].parse_as == "bool"
    assert CONFIG_FIELD_MAP["CHAT_EXPERT_FORCE_AGENTIC_RAG"].parse_as == "bool"
